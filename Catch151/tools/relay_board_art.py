#!/usr/bin/env python3
"""Writes relay/src/board_art.js: what the relay's leaderboard picture (/board.svg) is drawn with. The game's 5x7 font (its
printable characters, from host/glcdfont.h) and each game's cartridge as the Games menu draws it, a small PNG cut out
along the cartridge's outline (see-through round it) from the menu's three pages (host_shot pictures of them: tools/relay_board_art.sh takes them and runs this).

usage: relay_board_art.py <page 1 .ppm> <page 2 .ppm> <page 3 .ppm>
"""
import base64
import io
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'relay', 'src', 'board_art.js')
# each game on the board (as the Games menu numbers them) and where its cartridge is: (page, x, y) of its top left
CARTS = {0: (0, 106, 96), 2: (0, 106, 238), 3: (1, 106, 96), 4: (0, 254, 238), 5: (1, 254, 96), 6: (1, 106, 238),
         7: (1, 254, 238), 8: (2, 106, 96)}
W, H = 58, 70  # half the cartridge's size on the menu


def font():
    src = open(os.path.join(ROOT, 'host', 'glcdfont.h')).read()
    b = [int(h, 16) for h in re.findall(r'0x([0-9A-Fa-f]{2})', src.split('{', 1)[1])]
    return b[32 * 5:127 * 5]  # the printable ones, space to tilde


def cart_mask():
    """The cartridge's own shape in the crop, as src/menus_v2.h v2Cart() draws it: 21 x 26 cells of 5 px with the
    notched top right corner, and its dark outline one cell round it. Everything else is the Game Boy's green screen
    behind it (Fedor: the board's cartridges had "some kind of green corner. Let's remove that"), left out."""
    def inside(cx, cy):
        return 0 <= cx < 21 and 0 <= cy < 26 and cx - 17 <= cy
    m = Image.new('L', (116, 141), 0)
    for py in range(141):
        for px in range(116):
            cx, cy = px // 5 - 1, py // 5 - 1
            if inside(cx, cy) or any(inside(cx + dx, cy + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                m.putpixel((px, py), 255)
    return m


MASK = None


def cart(page, x, y):
    global MASK
    MASK = MASK or cart_mask()
    im = page.crop((x - 5, y - 5, x + 111, y + 136))
    # outside the shape: the outline's ink (so halving it blends the edge into the outline, not into the green), then
    # see-through
    ink = Image.new('RGB', im.size, (0x1B, 0x1B, 0x25))
    im = Image.composite(im, ink, MASK).convert('RGBA')
    im.putalpha(MASK)
    im = im.resize((W, H), Image.BOX)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def main():
    pages = [Image.open(p).convert('RGB') for p in sys.argv[1:4]]
    f = font()
    lines = [
        '// GENERATED by tools/relay_board_art.py (tools/relay_board_art.sh): do not edit. What /board.svg is drawn with:',
        "// the game's 5x7 font (host/glcdfont.h), space to tilde, 5 columns a character, the top row the low bit; and each",
        "// game's cartridge as the Games menu draws it, by the game's number there.",
        'export const FONT = [' + ', '.join(str(v) for v in f) + '];',
        f'export const CART_W = {W}, CART_H = {H};',
        'export const CART = {',
    ]
    for g, (p, x, y) in CARTS.items():
        lines.append(f"  {g}: '{cart(pages[p], x, y)}',")
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(OUT, os.path.getsize(OUT), 'bytes')


main()
