#!/usr/bin/env python3
"""Writes relay/src/board_art.js: what the relay's world board (/board.svg) is drawn with. The game's 5x7 font (its
printable characters, from host/glcdfont.h) and each game's cartridge as the Games menu draws it, a small PNG cropped
from the menu's two pages (host_shot pictures of them: tools/relay_board_art.sh takes them and runs this).

usage: relay_board_art.py <page 1 .ppm> <page 2 .ppm>
"""
import base64
import io
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'relay', 'src', 'board_art.js')
# each game on the board (as the Games menu numbers them) and where its cartridge is: (page, x, y) of its top left
CARTS = {0: (0, 106, 96), 2: (0, 106, 238), 3: (1, 106, 96), 4: (0, 254, 238), 5: (1, 254, 96), 6: (1, 106, 238)}
W, H = 58, 70  # half the cartridge's size on the menu


def font():
    src = open(os.path.join(ROOT, 'host', 'glcdfont.h')).read()
    b = [int(h, 16) for h in re.findall(r'0x([0-9A-Fa-f]{2})', src.split('{', 1)[1])]
    return b[32 * 5:127 * 5]  # the printable ones, space to tilde


def cart(page, x, y):
    im = page.crop((x - 5, y - 5, x + 111, y + 136)).resize((W, H), Image.BOX)
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def main():
    pages = [Image.open(p).convert('RGB') for p in sys.argv[1:3]]
    f = font()
    lines = [
        '// GENERATED by tools/relay_board_art.py (tools/relay_board_art.sh): do not edit. What /board.svg is drawn with:',
        "// the game's 5x7 font (host/glcdfont.h), space to tilde, 5 columns a character, the top row the low bit; and each",
        "// game's cartridge as the Games menu draws it, by the game's number there.",
        'export const FONT = [' + ', '.join(str(v) for v in f) + '];',
        f'export const CART_W = {W}, CART_H = {H};',
        'export const CART = {',
    ]
    for g, (p, x, y) in CARTS.items():
        lines.append(f"  {g}: '{cart(pages[p], x, y)}',")
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print(OUT, os.path.getsize(OUT), 'bytes')


main()
